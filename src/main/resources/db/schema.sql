-- ---------- Séquences (utilisées explicitement par l'application) ----------
CREATE SEQUENCE seq_user      START WITH 10 INCREMENT BY 1;
CREATE SEQUENCE seq_annee     START WITH 10 INCREMENT BY 1;
CREATE SEQUENCE seq_trimestre START WITH 10 INCREMENT BY 1;
CREATE SEQUENCE seq_paiement  START WITH 1  INCREMENT BY 1;
CREATE SEQUENCE seq_versement START WITH 1  INCREMENT BY 1;

-- ---------- Comptes utilisateurs ----------
-- Identifiants des comptes ENSEIGNANT générés par IDENTITY (à partir de 1000),
-- ceux du directeur / admin / financier par seq_user : pas de collision.
CREATE TABLE user_account (
    id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    login     VARCHAR2(50)  NOT NULL,
    password  VARCHAR2(255) NOT NULL,
    role      VARCHAR2(20)  NOT NULL,
    CONSTRAINT uq_user_login UNIQUE (login),
    CONSTRAINT chk_user_role CHECK (role IN ('ADMIN','ENSEIGNANT','FINANCIER','DIRECTEUR'))
);

CREATE TABLE app_settings (
    cle     VARCHAR2(50) PRIMARY KEY,
    valeur  VARCHAR2(10) DEFAULT 'true'
);

-- ---------- Organisation scolaire ----------
CREATE TABLE annee_scolaire (
    id       NUMBER PRIMARY KEY,
    libelle  VARCHAR2(20) NOT NULL UNIQUE
);

CREATE TABLE trimestre (
    id        NUMBER PRIMARY KEY,
    numero    NUMBER(1) NOT NULL,
    annee_id  NUMBER NOT NULL REFERENCES annee_scolaire(id),
    CONSTRAINT uq_trimestre UNIQUE (numero, annee_id)
);

CREATE TABLE niveau (
    id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle  VARCHAR2(50) NOT NULL,
    prix     NUMBER(10,2) DEFAULT 0
);

CREATE TABLE matiere (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom        VARCHAR2(100) NOT NULL,
    niveau_id  NUMBER NOT NULL REFERENCES niveau(id)
);

CREATE TABLE classe (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom        VARCHAR2(50) NOT NULL,
    niveau_id  NUMBER NOT NULL REFERENCES niveau(id),
    annee_id   NUMBER NOT NULL REFERENCES annee_scolaire(id)
);

-- ---------- Élèves ----------
CREATE TABLE eleve (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom             VARCHAR2(100) NOT NULL,
    prenom          VARCHAR2(100) NOT NULL,
    date_naissance  DATE,
    adresse         VARCHAR2(255),
    telephone       VARCHAR2(30),
    matricule       VARCHAR2(20)
);

CREATE TABLE inscription (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleve_id          NUMBER NOT NULL REFERENCES eleve(id),
    annee_id          NUMBER NOT NULL REFERENCES annee_scolaire(id),
    niveau_id         NUMBER NOT NULL REFERENCES niveau(id),
    mode_paiement     VARCHAR2(30),
    date_inscription  DATE DEFAULT SYSDATE
);

CREATE TABLE affectation_eleve (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleve_id          NUMBER NOT NULL REFERENCES eleve(id),
    classe_id         NUMBER NOT NULL REFERENCES classe(id),
    date_affectation  DATE DEFAULT SYSDATE,
    date_fin          DATE
);

-- ---------- Enseignants ----------
CREATE TABLE enseignant (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR2(20),
    nom        VARCHAR2(100) NOT NULL,
    prenom     VARCHAR2(100) NOT NULL,
    telephone  VARCHAR2(30),
    user_id    NUMBER NOT NULL REFERENCES user_account(id)
);

CREATE TABLE enseignant_classe_matiere (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enseignant_id  NUMBER NOT NULL REFERENCES enseignant(id),
    classe_id      NUMBER NOT NULL REFERENCES classe(id),
    matiere_id     NUMBER NOT NULL REFERENCES matiere(id),
    annee_id       NUMBER NOT NULL REFERENCES annee_scolaire(id)
);

-- ---------- Notes ----------
CREATE TABLE note (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleve_id      NUMBER NOT NULL REFERENCES eleve(id),
    matiere_id    NUMBER NOT NULL REFERENCES matiere(id),
    classe_id     NUMBER NOT NULL REFERENCES classe(id),
    trimestre_id  NUMBER NOT NULL REFERENCES trimestre(id),
    valeur        NUMBER(5,2),
    validee       NUMBER(1) DEFAULT 0,
    observation   VARCHAR2(255)
);

-- ---------- Finances ----------
CREATE TABLE versement (
    id              NUMBER PRIMARY KEY,
    annee_id        NUMBER REFERENCES annee_scolaire(id),
    type_versement  VARCHAR2(20),
    montant         NUMBER(12,2),
    banque          VARCHAR2(100),
    num_bon         VARCHAR2(50),
    date_versement  DATE DEFAULT SYSDATE
);

CREATE TABLE paiement (
    id                NUMBER PRIMARY KEY,
    eleve_id          NUMBER NOT NULL REFERENCES eleve(id) ON DELETE CASCADE,
    annee_id          NUMBER NOT NULL REFERENCES annee_scolaire(id),
    montant           NUMBER(12,2) NOT NULL,
    date_paiement     TIMESTAMP DEFAULT SYSTIMESTAMP,
    mode_paiement     VARCHAR2(30),
    commentaire       VARCHAR2(255),
    statut_versement  VARCHAR2(20) DEFAULT 'EN_CAISSE',
    versement_id      NUMBER REFERENCES versement(id)
);

